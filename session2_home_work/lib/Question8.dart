// Write a Dart program that declares two numeric variables and performs addition, subtraction, multiplication, division, and modulo on them. Print each result.
void main() {
  int num1 = 10;
  int num2 = 15;
  int sum = num1 + num2;
  print(sum);
  int subtraction = num2 - num1;
  print(subtraction);
  int multiplication = num1 * num2;
  print(multiplication);
  //use double becuase Fractional number
  double division = num2 / num2;
  print(division);
  int modulo = num2 % num1;
  print(modulo);
}
